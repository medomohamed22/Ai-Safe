import assert from 'node:assert/strict';
import vm from 'node:vm';
import { importOpenApi, createBackend, backendBootstrap } from '../src/lib/backend.ts';
const config = importOpenApi(JSON.stringify({openapi:'3.0.0',servers:[{url:'https://example.test/v1'}],paths:{'/items':{get:{operationId:'list'},post:{operationId:'create'}},'/items/{id}':{get:{operationId:'read'},patch:{operationId:'edit'},delete:{operationId:'remove'}}}}));
const api = createBackend(config,()=>{throw new Error('Demo must not use network');});
const item = await api.request('create',{body:{name:'One'}});
assert.equal((await api.request('list')).length,1);
await api.request('edit',{params:{id:item.id},body:{name:'Two'}});
assert.equal((await api.request('read',{params:{id:item.id}})).name,'Two');
await api.request('remove',{params:{id:item.id}});
assert.deepEqual(await api.request('list'),[]);
const real = {...config,mode:'http',endpoints:config.endpoints.map(e=>({...e,dataPath:'data',fields:{name:'full_name'}}))};
let requested;
const http = createBackend(real,async (url,init)=>{requested={url:String(url),init};return new Response(JSON.stringify({data:[{id:1,full_name:'Mapped'}]}));});
assert.equal((await http.request('list',{query:{q:'a b'}}))[0].name,'Mapped');
assert.equal(requested.url,'https://example.test/v1/items?q=a+b');
await assert.rejects(()=>http.request('read'),/Missing path parameter/);
await assert.rejects(()=>createBackend(real,async()=>new Response('Denied',{status:403})).request('list'),/403/);
assert.equal(await createBackend(real,async()=>new Response(null,{status:204})).request('remove',{params:{id:'1'}}),null);
const context = {crypto,fetch}; vm.runInNewContext(backendBootstrap(config),context); assert.equal(typeof context.__S2UI_API__.request,'function');
assert.throws(()=>importOpenApi('{}'),/OpenAPI/);
console.log('PASS: OpenAPI import, network-free demo CRUD, HTTP URL/query mapping, field mapping, errors, 204 and export runtime. HTTP checks use local mocked responses.');
