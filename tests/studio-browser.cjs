const { chromium, chromePath } = require('./browser-runtime.cjs');
const assert = require('node:assert/strict');
const url = process.env.S2UI_TEST_URL || 'http://127.0.0.1:5173';
(async () => {
 const browser = await chromium.launch({ executablePath: chromePath, headless: true });
 try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(20000);
  await page.addInitScript(() => {
   localStorage.setItem('s2ui.versions.v1', JSON.stringify(["import {useState} from 'react';export default function App(){const [n,setN]=useState(0);return <main><h1>Studio fixture</h1><button onClick={()=>setN(n+1)}>Increment</button><output>{n}</output></main>}"]));
   localStorage.setItem('s2ui.vindex.v1', '0');
  });
  await page.goto(url);
  const frame = page.frameLocator('iframe[title="Live preview"]');
  await frame.getByRole('button', { name: 'Increment', exact: true }).click({ timeout: 60000 });
  const separator = page.getByRole('separator', { name: 'Resize drawing and preview' });
  await separator.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await separator.getAttribute('aria-valuenow'), '42');
  const box = await separator.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 30); await page.mouse.down();
  await page.mouse.move(box.x + 100, box.y + 30); await page.mouse.up();
  assert.ok(Number(await separator.getAttribute('aria-valuenow')) > 42);
  await page.getByRole('button', { name: 'Expand preview', exact: true }).click();
  assert.equal(await page.locator('.sketch-panel').isVisible(), false);
  assert.equal(await frame.locator('output').textContent(), '1');
  await page.getByRole('button', { name: 'Split workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  assert.equal(await page.locator('.studio-body').getAttribute('data-sidebar-collapsed'), 'true');
  await page.reload();
  assert.equal(await page.locator('.studio-body').getAttribute('data-sidebar-collapsed'), 'true');
  assert.ok(Number(await separator.getAttribute('aria-valuenow')) > 42);
  await page.locator('.export-menu > summary').click();
  assert.equal(await page.getByRole('button', { name: 'Project ZIP', exact: true }).isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.export-menu').getAttribute('open'), null);
  await page.getByRole('button', { name: 'Select element', exact: true }).click();
  await frame.getByRole('heading', { name: 'Studio fixture' }).click();
  await page.getByRole('region', { name: 'Element editor' }).waitFor();
  assert.ok((await page.locator('.element-inspector').boundingBox()).width >= 190);
  await page.getByRole('button', { name: 'Close element editor' }).click();
  await page.getByRole('button', { name: 'Select element', exact: true }).click();
  await frame.getByRole('button', { name: 'Increment', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Show instructions workspace' }).click();
  await page.getByLabel('Describe your interface').fill('Keep this draft');
  await page.screenshot({ path: 'tests/studio-mobile-instructions.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Show sketch workspace' }).click();
  await page.getByRole('button', { name: 'Show preview workspace' }).click();
  assert.equal(await frame.locator('output').textContent(), '1', 'Mobile navigation must retain the running preview');
  await page.getByRole('button', { name: 'Show instructions workspace' }).click();
  assert.equal(await page.getByLabel('Describe your interface').inputValue(), 'Keep this draft');
  await page.getByRole('button', { name: 'Open workspace tools' }).click();
  const tools = page.getByRole('dialog', { name: 'Workspace tools', exact: true });
  await tools.waitFor(); await page.screenshot({ path: 'tests/studio-mobile-tools.png', animations: 'disabled' });
  for (let i = 0; i < 20; i++) await page.keyboard.press('Tab');
  assert.equal(await tools.evaluate(el => el.contains(document.activeElement)), true);
  await page.keyboard.press('Escape'); await tools.waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: 'Open workspace tools' }).evaluate(el => el === document.activeElement), true);
  await page.getByRole('button', { name: 'Show preview workspace' }).click();
  await page.getByRole('button', { name: 'Select element', exact: true }).click();
  await frame.getByRole('heading', { name: 'Studio fixture' }).click();
  const inspector = page.getByRole('region', { name: 'Element editor' }); await inspector.waitFor();
  await page.getByLabel('Element text', { exact: true }).fill('Edited on phone');
  await page.getByRole('button', { name: 'Apply to code', exact: true }).click();
  await frame.getByRole('heading', { name: 'Edited on phone' }).waitFor();
  await page.setViewportSize({ width: 390, height: 500 });
  await page.getByRole('button', { name: 'Show instructions workspace' }).click();
  assert.ok((await page.getByRole('button', { name: 'Send', exact: true }).boundingBox()).y < 440, 'Generation remains reachable with a shorter viewport');
  console.log('PASS: split resize by keyboard/pointer and persistence, focus layout, sidebar persistence, export menu, contextual inspector, phone bottom navigation/draft/preview preservation, tools focus trap and phone source edits.');
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
